async function onImportData(){
    
    for(i = 0; i < ids.length; i++){
        await onGetData(ids[i]);
    }
}

async function onGetData(id){

    let config = {
        method: 'get',
        maxBodyLength: Infinity,
        url: urlBase + `cadastros/Produto/GetCopy?doID=${idbase}&pID=${id}&pComposicao=1&pComissoes=1&pConvenios=1`,
        headers: { 
          'DoToken': token, 
          'Authorization': basicToken
        },
        httpsAgent: agent
      };
      
      await axios.request(config)
      .then((response) => {
        if(response.data.RetWm === "success"){
            var data = JSON.stringify(response.data.obj);
            /* var data = JSON.stringify(response.data.obj)
            .replace('"AddMode":false','"AddMode":true')
            .replace('"EditMode":true','"EditMode":false') */
            
            onSaveData(data);
        }
      })
      .catch((error) => {
        console.log(error);
      });
}

async function onSaveData(data){
    
    let config = {
        method: 'post',
        maxBodyLength: Infinity,
        url: urlBase + `cadastros/Produto/SaveData?doID=${idbase}&doIDUser=-100`,
        headers: { 
          'DoToken': token, 
          'Authorization': basicToken,
          'Content-Type': 'application/json'
        },
        httpsAgent: agent,
        data : data
      };
      
      axios.request(config)
      .then((response) => {
        if(response.data.RetWm === "success"){
            console.log("OK");
        }
      })
      .catch((error) => {
        console.log(error);
      });
}